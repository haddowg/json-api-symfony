<?php

declare(strict_types=1);

namespace haddowg\JsonApiBundle\OpenApi;

use haddowg\JsonApiBundle\Server\ServerProvider;
use Symfony\Component\Routing\Exception\ExceptionInterface as RoutingException;
use Symfony\Component\Routing\Generator\UrlGeneratorInterface;

/**
 * The URLs a server's OpenAPI document is served at, as JSON and as YAML: what the bundle's
 * viewer offers as downloads, and what an app's own documentation page can link to.
 *
 * A URL is the path of the bundle's document route for the server when the
 * `jsonapi_openapi` routes are imported. Otherwise it is the path of the app's own route to
 * {@see \haddowg\JsonApiBundle\Controller\OpenApiController} that serves the server in that
 * format, found by its controller, its `server` default and its `format` default
 * ({@see DocumentRouteLocator}). Either way it is generated by the router, so it is
 * host-relative and carries the current request's script base and any import prefix. In
 * combined mode every server gets the one combined document's URLs.
 *
 * {@see yaml()} is null when YAML isn't served (`json_api.openapi.yaml.enabled` off, or
 * the expose gate closed), and either URL is null when no route serves the document.
 */
final readonly class DocumentUrls
{
    /**
     * @param bool $enabled  `json_api.openapi.enabled`
     * @param bool $yaml     `json_api.openapi.yaml.enabled`
     * @param bool $exposed  the expose gate: `kernel.debug` or `json_api.openapi.expose_in_prod`
     * @param bool $combined `json_api.openapi.multi_server === combined`
     */
    public function __construct(
        private UrlGeneratorInterface $urlGenerator,
        private bool $enabled = true,
        private bool $yaml = false,
        private bool $exposed = true,
        private bool $combined = false,
        private ?DocumentRouteLocator $routes = null,
    ) {}

    /**
     * The URL of `$server`'s JSON document (the default server when null), or null when
     * no route serves it.
     */
    public function json(?string $server = null): ?string
    {
        return $this->enabled ? $this->url(DocumentFormat::Json, $server ?? ServerProvider::DEFAULT_SERVER) : null;
    }

    /**
     * The URL of `$server`'s YAML document (the default server when null), or null when
     * YAML isn't served or no route serves it.
     */
    public function yaml(?string $server = null): ?string
    {
        return $this->enabled && $this->yaml && $this->exposed ? $this->url(DocumentFormat::Yaml, $server ?? ServerProvider::DEFAULT_SERVER) : null;
    }

    /**
     * The document's downloads in the shape of ReDoc's `downloadUrls` option: JSON, then
     * YAML when it is served.
     *
     * @return list<array{title: string, url: string}>
     */
    public function downloads(?string $server = null): array
    {
        $downloads = [];
        foreach (['JSON' => $this->json($server), 'YAML' => $this->yaml($server)] as $title => $url) {
            if ($url !== null) {
                $downloads[] = ['title' => $title, 'url' => $url];
            }
        }

        return $downloads;
    }

    private function url(DocumentFormat $format, string $server): ?string
    {
        $prefix = $format === DocumentFormat::Json ? 'jsonapi.openapi.' : 'jsonapi.openapi.yaml.';

        try {
            if (!$this->combined && $server !== ServerProvider::DEFAULT_SERVER) {
                return $this->urlGenerator->generate($prefix . 'server', ['server' => $server]);
            }

            return $this->urlGenerator->generate($prefix . 'default');
        } catch (RoutingException) {
        }

        $route = $this->routes?->find($server, $format);
        if ($route === null) {
            return null;
        }

        try {
            return $this->urlGenerator->generate($route['route'], $route['parameters']);
        } catch (RoutingException) {
            return null;
        }
    }
}
